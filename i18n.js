const LANGUAGES = [
  { id: 'de', name: 'Deutsch' },
  { id: 'en', name: 'English' }
];

// Text holen und Platzhalter {name} füllen. Fehlt ein Text in einer Sprache, wird Deutsch genommen.
function tr(lang, key, vars) {
  const dict = I18N[lang] || I18N.de;
  let s = dict[key];
  if (s === undefined) s = I18N.de[key];
  if (s === undefined) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m));
  return s;
}

// Fehlercodes des Updaters ("timeout", "http:403", "download:404", "incomplete") lesbar machen
function errorText(lang, code) {
  const c = String(code || '');
  if (!c) return tr(lang, 'err.unknown');
  if (c === 'timeout') return tr(lang, 'err.timeout');
  if (c === 'incomplete') return tr(lang, 'err.incomplete');
  if (c.startsWith('http:')) return tr(lang, 'err.http', { s: c.slice(5) });
  if (c.startsWith('download:')) return tr(lang, 'err.download', { s: c.slice(9) });
  return c;
}

// Statische Texte einer Seite setzen: data-i18n (Text), data-i18n-title, data-i18n-placeholder
function applyI18n(root, lang, vars) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = tr(lang, el.dataset.i18n, vars); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = tr(lang, el.dataset.i18nTitle, vars); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = tr(lang, el.dataset.i18nPlaceholder, vars); });
  if (root.documentElement) root.documentElement.lang = lang;
}

